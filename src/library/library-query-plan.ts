import type {DatabaseSync} from 'node:sqlite';
import type {CatalogRepository} from './catalog.js';
import type {ListRequest} from '../shared/contracts.js';
import {musicFilterTimeAnchor} from '../shared/music-filters.js';
import {musicFilterPlan} from './music-filters.js';
import {librarySortOrder,librarySortPrefix} from './natural-sort.js';
import {recallSpelling,type SpellingHit} from './search-spelling.js';
import {latinSearchQuery,SEARCH_ALGORITHM} from './search-text.js';
import {literalSearchVariants} from './search-normalization.js';
import {genreItemCondition} from './genre-query.js';
const normalize=(v:string)=>v.normalize('NFKC').toLowerCase().trim();
const artistRoles=['performer','album_artist','composer','conductor','orchestra'];
const likePattern=(s:string)=>`%${s.replace(/[\\%_]/g,'\\$&')}%`;
export type ItemMembership={sql:string;params:Array<string|number>};
export function libraryQueryPlan(db:DatabaseSync,catalog:CatalogRepository,request:ListRequest,membership?:ItemMembership,asOfMs=musicFilterTimeAnchor(),projection:'items'|'ids'='items'){
    const params: Array<string | number> = [],q=normalize(request.query ?? '');
    if(request.artistRole&&!artistRoles.includes(request.artistRole))throw new Error('无效艺人角色');
    const personal=request.view==='favorites'||request.view==='playlists';
    const where = personal?['1=1']:["p.visible=1 AND p.library_state='active'"];
    if(request.releaseTrackId){where.push('p.release_track_id=?');params.push(request.releaseTrackId);}
    if(request.view==='favorites')where.push('u.favorite=1');
    if(request.view==='playlists'){where.push('pj.playlist_id=?');params.push(request.value!);}
    if (request.view === 'artists' && (request.facetId||request.value)) {
      const album=request.artistRole==='album_artist';
      where.push(`EXISTS(SELECT 1 FROM artist_credit_member c LEFT JOIN artist_identity_binding ai ON ai.source_artist_id=c.artist_id
        JOIN artist a ON a.id=COALESCE(ai.identity_artist_id,c.artist_id)
        WHERE (c.credit_id=${album?'cr.artist_credit_id':'p.artist_credit_id'}${album?'':catalog.recordingCreditCondition()}) AND c.role=? AND ${request.facetId?'a.id':'a.name'}=?)`);
      params.push(request.artistRole??'performer',request.facetId??request.value!);
    }
    if (request.view === 'albums' && (request.facetId||request.value)) { where.push(`${request.facetId?'cr.id':'cr.title'}=?`); params.push(request.facetId??request.value!); }
    if(request.view==='albumGroups'){
      where.push('cr.group_id IS NOT NULL');
      if(request.facetId||request.value){where.push(`${request.facetId?'cg.id':'cg.title'}=?`);params.push(request.facetId??request.value!);}
    }
    if(request.genreFilter!==undefined){
      const filter=request.genreFilter;
      if(!filter||!Array.isArray(filter.ids)||filter.ids.length>16||filter.ids.some(value=>typeof value!=='string'||!value.length||value.length>128)||new Set(filter.ids).size!==filter.ids.length||!['any','all'].includes(filter.operator)||typeof filter.descendants!=='boolean')throw new Error('风格组合最多 16 项，且需要明确交集或并集');
      if(filter.ids.length){
        const clauses=filter.ids.map(genreId=>{params.push(genreId);return genreItemCondition('SELECT id FROM genre WHERE id=? AND archived=0',filter.descendants);});
        where.push('('+clauses.join(filter.operator==='all'?' AND ':' OR ')+')');
      }
    }else if (request.view === 'genres' && (request.facetId||request.value)) {
      where.push(genreItemCondition(request.facetId?'SELECT id FROM genre WHERE id=?':'SELECT genre_id FROM genre_name_alias WHERE normalized_name=?',true,false));params.push(request.facetId??normalize(request.value!));
    }
    if (request.view === 'folders' && request.value) { where.push('r.id=?'); params.push(request.value); }
    if(request.filters!==undefined){const filters=musicFilterPlan(request.filters,catalog.recordingCreditCondition(),asOfMs);where.push(...filters.where);params.push(...filters.params);}
    if(membership){where.push(`p.id IN(${membership.sql})`);params.push(...membership.params);}
    const order=librarySortOrder(request.sort,request.view);
    // These references are generated by private plans, never by raw user SQL.
    // Count and ID pages only join rows their filters/ranking/order actually use.
    // Full item projection (including repeated playlist entries) stays intact.
    let searchCandidates=false;
    const joinsFor=(references:string,full=false,filterCandidates=true):string=>{
      const uses=(alias:string)=>full||new RegExp(`\\b${alias}\\.`).test(references);
      const media=uses('f')||uses('r'),release=uses('ct')||uses('cm')||uses('cr')||uses('cg');
      return `FROM ${searchCandidates&&filterCandidates?'search_candidates matches CROSS JOIN ':''}playable_item p ${q?'INDEXED BY playable_item_search_cover ':''}${searchCandidates&&filterCandidates?'ON p.id=matches.item_id':''}
       ${media?'JOIN media_file f ON f.id=p.file_id':''} ${uses('r')?'JOIN library_root r ON r.id=f.root_id':''}
       ${uses('o')?'LEFT JOIN metadata_override o ON o.item_id=p.id':''} ${uses('u')?'LEFT JOIN item_user_state u ON u.item_id=p.id':''}
       ${release?'LEFT JOIN release_track ct ON ct.id=p.release_track_id LEFT JOIN medium cm ON cm.id=ct.medium_id LEFT JOIN release cr ON cr.id=cm.release_id':''}
       ${uses('cg')?'LEFT JOIN release_group cg ON cg.id=cr.group_id':''} ${uses('sk')?'LEFT JOIN item_sort_key sk ON sk.item_id=p.id':''}
       ${/\bps\./.test(references)?'LEFT JOIN playback_item_stats ps ON ps.item_id=p.id':''} ${request.view==='playlists'?'JOIN playlist_item pj ON pj.item_id=p.id':''}`;
    };
    let cte='',directParams:Array<string|number>=[],spelling:SpellingHit[]=[],rank='',distance='';
    if (q) {
      const literalQueries=literalSearchVariants(q);
      const isShortHan = [...q].length <= 2 && [...q].every(c => /\p{Script=Han}/u.test(c));
      const roman=latinSearchQuery(q),escape=/[\\%_]/.test(q)?" ESCAPE '\\'":'';
      let direct=literalQueries.map(()=>`SELECT item_id FROM search_fts WHERE ${['title','artist','album','genre'].map(field=>`${field} LIKE ?${escape}`).join(' OR ')}`).join(' UNION ');
      directParams=literalQueries.flatMap(query=>Array(4).fill(likePattern(query)));
      if(isShortHan){direct=`SELECT item_id FROM search_gram WHERE gram IN(${literalQueries.map(()=>'?').join(',')})`;directParams=literalQueries;}
      else if(roman){direct+=` UNION SELECT f.item_id FROM search_latin_fts f JOIN search_latin l ON l.item_id=f.item_id WHERE l.algorithm=? AND f.roman LIKE ? UNION SELECT f.item_id FROM search_latin_fts f JOIN search_latin l ON l.item_id=f.item_id WHERE l.algorithm=? AND f.initials LIKE ?`;directParams.push(SEARCH_ALGORITHM,likePattern(roman),SEARCH_ALGORITHM,likePattern(roman));}
      cte=`WITH direct_matches(item_id) AS(${direct}) `;
      spelling=recallSpelling(db,q,`${joinsFor(where.join(' '))} WHERE ${where.join(' AND ')}`,params);
      cte=cte.trimEnd()+`,search_candidates(item_id) AS(SELECT DISTINCT item_id FROM direct_matches${spelling.length?` UNION SELECT column1 FROM(VALUES ${spelling.map(()=>'(?)').join(',')})`:''}) `;
      directParams.push(...spelling.map(hit=>hit.id));searchCandidates=true;
      if(spelling.length)distance=`CASE p.id ${spelling.map(()=> 'WHEN ? THEN ?').join(' ')} ELSE 0 END`;
      // Direct matches always precede spelling recall, preserving precise results.
      const directRank=`aural_search_rank_v1(COALESCE(o.title,p.title),COALESCE(o.artist,p.artist),COALESCE(o.album,p.album),p.genre,?)`;
      // With no spelling hits, every candidate already came from direct_matches.
      // Avoid rebuilding and probing that same membership set for every rank.
      rank=spelling.length?`CASE WHEN p.id IN(SELECT item_id FROM direct_matches) THEN ${directRank} ELSE 10 END`:directRank;
    }
    const collapse=request.collapseVersions===true&&request.view!=='playlists';
    const filterReferences=where.join(' ')+(collapse?' f.status r.status':''),filtered=`${joinsFor(filterReferences)} WHERE ${where.join(' AND ')}`;
    const collapsed=collapse?` AND p.id IN(SELECT v.id FROM(SELECT p.id,
      ROW_NUMBER() OVER(PARTITION BY p.release_track_id ORDER BY (f.status='online' AND r.status!='offline') DESC,p.id) rn ${filtered}) v WHERE v.rn=1)`:'';
    const countFrom=filtered+collapsed;
    const from=`${joinsFor(filterReferences+' '+order+' '+rank,projection==='items')} WHERE ${where.join(' AND ')}`+collapsed;
    const prefix=projection==='ids'?librarySortPrefix(request.sort,request.view):null;
    let prefixPage:string|null=null;
    if(prefix){
      // Probe only the requested prefix positions, then expand both complete
      // boundary buckets. Count earlier buckets to preserve the exact offset
      // after applying the original secondary order. Never cut through ties.
      const prefixOrder=`${rank?'search_rank,':''}${distance?'search_distance,':''}sort_prefix ${prefix.direction}`;
      const prefixFields=[...(rank?['search_rank']:[]),...(distance?['search_distance']:[]),'sort_prefix'];
      const compare=(left:string,right:string,before:boolean,equal=false)=>'('+prefixFields.map((field,index)=>{
        const asc=field!=='sort_prefix'||prefix.direction==='ASC',op=before===asc?'<':'>';
        return '('+[...prefixFields.slice(0,index).map(previous=>`${left}.${previous}=${right}.${previous}`),`${left}.${field}${op}${equal&&index===prefixFields.length-1?'=':''}${right}.${field}`].join(' AND ')+')';
      }).join(' OR ')+')';
      const reversePrefixOrder=prefixFields.map(field=>`${field} ${field==='sort_prefix'?(prefix.direction==='ASC'?'DESC':'ASC'):'DESC'}`).join(',');
      // Probe from the closer end of this exact candidate snapshot. Reversing
      // the prefix probe does not reverse the final page: expand both entire
      // tied buckets and apply the original secondary order below as before.
      const probeOrder=request.offset?prefixFields.flatMap(field=>{
        const ascending=field!=='sort_prefix'||prefix.direction==='ASC';
        return [`CASE WHEN bounds.requested_offset<=bounds.total/2 THEN candidate.${field} END ${ascending?'ASC':'DESC'}`,
          `CASE WHEN bounds.requested_offset>bounds.total/2 THEN candidate.${field} END ${ascending?'DESC':'ASC'}`];
      }).join(','):prefixOrder;
      const finalOrder=`${rank?'page.search_rank,':''}${distance?'page.search_distance,':''}${order}`;
      const candidates=`${joinsFor(filterReferences+' '+prefix.sql+' '+rank)} WHERE ${where.join(' AND ')}`+collapsed;
      const pageJoins=joinsFor(order,false,false).replace('FROM playable_item p ','FROM page_slice page CROSS JOIN playable_item p ');
      prefixPage=`${cte?cte.trimEnd()+',':'WITH'} page_candidates AS MATERIALIZED(
        SELECT p.id${rank?`,${rank} search_rank`:''}${distance?`,${distance} search_distance`:''},${prefix.sql} sort_prefix ${candidates}
       ),page_total AS MATERIALIZED(SELECT COUNT(*) total FROM page_candidates),
       page_window AS MATERIALIZED(SELECT ? requested_limit,? requested_offset,total FROM page_total),
       page_probe AS MATERIALIZED(SELECT candidate.* FROM page_candidates candidate CROSS JOIN page_window bounds
         ORDER BY ${probeOrder} LIMIT (SELECT MIN(requested_limit,MAX(0,total-requested_offset)) FROM page_window)
         OFFSET (SELECT CASE WHEN requested_offset>total/2 THEN MAX(0,total-requested_offset-requested_limit) ELSE requested_offset END FROM page_window)),
       page_lower AS MATERIALIZED(SELECT * FROM page_probe ORDER BY ${prefixOrder} LIMIT 1),
       page_upper AS MATERIALIZED(SELECT * FROM page_probe ORDER BY ${reversePrefixOrder} LIMIT 1),
       page_skip AS(SELECT COUNT(*) skipped FROM page_candidates candidate CROSS JOIN page_lower lower WHERE ${compare('candidate','lower',true)}),
       page_slice AS MATERIALIZED(SELECT candidate.* FROM page_candidates candidate CROSS JOIN page_lower lower CROSS JOIN page_upper upper WHERE ${compare('candidate','lower',false,true)} AND ${compare('candidate','upper',true,true)}),
       page_results AS MATERIALIZED(SELECT p.id${rank?',page.search_rank search_rank':''}${distance?',page.search_distance search_distance':''},ROW_NUMBER() OVER(ORDER BY ${finalOrder}) page_ordinal ${pageJoins} WHERE p.id=page.id
       ORDER BY ${finalOrder} LIMIT ? OFFSET (? - (SELECT skipped FROM page_skip)))
       SELECT page_results.*,page_total.total FROM page_total LEFT JOIN page_results ON 1=1 ORDER BY page_ordinal`;
    }
    const queryParams=[...directParams,...(collapse?[...params,...params]:params)];
    return {params,order,q,cte,directParams,spelling,rank,distance,collapse,from,countFrom,prefixPage,queryParams};
}
